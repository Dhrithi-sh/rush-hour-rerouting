"""Write RESULTS_AND_INFORMATION.md: project context, every figure, and the key numbers.

    python report/build_summary.py [--results results] [--out RESULTS_AND_INFORMATION.md]

Like the Word report, every number here is read from the results folder, so the
document is regenerated (by run_all.py) whenever the experiments are re-run.
"""
from __future__ import annotations

import argparse
import json
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
MODE = {"single": "Scattered closures", "cluster": "Accident zone", "wave": "Congestion wave",
        "tree": "Tree-edge closures"}
METHOD = {"sequential": "per-edge repair", "batch": "batch repair"}


def x(v) -> str:
    if v is None or pd.isna(v):
        return "–"
    return f"{v:,.0f}×" if v >= 10 else f"{v:.1f}×"


def be(v, hi) -> str:
    return f"≈ {v:,.0f}" if v else f"> {hi:,} (not reached)"


def table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def build(res: str, out: str) -> None:
    rel = os.path.relpath(res, os.path.dirname(os.path.abspath(out))).replace(os.sep, "/")
    fig = lambda name: f"{rel}/{name}"                                  # noqa: E731
    opt = lambda name: pd.read_csv(os.path.join(res, name)) if os.path.exists(os.path.join(res, name)) else None  # noqa: E731
    M = json.load(open(os.path.join(res, "meta.json"), encoding="utf-8"))
    summ = pd.read_csv(os.path.join(res, "summary_main.csv"))
    rp = pd.read_csv(os.path.join(res, "raw_ripple.csv"))
    sc = pd.read_csv(os.path.join(res, "raw_scaling.csv"))
    fleet, p2p, closure = opt("raw_fleet.csv"), opt("raw_p2p.csv"), opt("raw_closure.csv")
    gstats, cross = opt("graph_stats.csv"), opt("summary_crossgraph.csv")
    sizes = sorted(summ["size"].unique())
    lo, hi = sizes[0], sizes[-1]
    modes = [m for m in MODE if m in set(summ["mode"])]
    methods = [m for m in METHOD if m in set(summ["method"])]
    blk = summ[summ["phase"] == "block"]

    def row(mode, size, method="sequential"):
        return blk[(blk["mode"] == mode) & (blk["size"] == size) & (blk["method"] == method)].iloc[0]

    closure_txt = "deleting it" if M.get("closure") == "delete" else f"{M['block_factor']}× its travel time"
    L = []
    add = L.append
    add("# Rush Hour Rerouting: results and information\n")
    add("*This file is generated by `report/build_summary.py` from `results/` (it is rewritten by every "
        "`python run_all.py`). Do not edit it by hand; edit the generator instead.*\n")
    commit = M.get("git_commit")
    add(f"Results produced by `{M.get('command', 'python run_all.py')}`"
        + (f" at commit `{commit[:7]}`" if commit else "")
        + f" in {M['runtime_seconds']:.0f} s on {M['platform']} (Python {M['python']}). "
        f"**{M['equality_checks_passed']:,} repair-versus-Dijkstra checks, zero mismatches.**\n")

    # ------------------------------------------------------------ context
    add("## 1. What the project is about\n")
    add("A routing service keeps the shortest travel times from a depot to every intersection, together with "
        "the shortest-path tree that gives each vehicle its route. When an accident blocks roads or congestion "
        "slows them down, those routes must be updated. The textbook answer is to rerun **Dijkstra's algorithm** "
        "from scratch. The alternative studied here is to **repair** only the part of the tree that the change "
        "actually affects (Ramalingam–Reps style incremental shortest paths).\n")
    add("We compare, on identical graph states and with every result checked against a fresh Dijkstra run:\n")
    add("- **Full Dijkstra** recomputation (baseline).\n"
        "- **Per-edge repair**: each changed road is repaired one at a time.\n"
        "- **Batch repair** (our addition): all roads of one disruption are repaired in a single sweep "
        "(proof of correctness in the report, Theorem 2).\n"
        "- For a single vehicle's route: **A\\*** from scratch and **LPA\\*** (Lifelong Planning A\\*), an "
        "incremental goal-directed search.\n")
    add("Disruption models: *scattered closures* (random roads), *accident zone* (a connected cluster of "
        "roads), *congestion wave* (slow-down fading with distance from an epicentre), and *tree-edge "
        "closures* (only roads that carry at least one shortest path — the honest worst-case-relevant case). "
        f"A closed road is modelled by **{closure_txt}** "
        "in the main experiments; a separate experiment compares that with true deletion.\n")

    # ------------------------------------------------------------ data
    add("## 2. Road networks\n")
    if gstats is not None:
        add(table(["Network", "Nodes", "Directed edges", "Avg. out-degree", "Hop diameter (≥)", "One-way edges"],
                  [[r["graph"].replace("_", " "), f"{int(r['n']):,}", f"{int(r['m']):,}", f"{r['avg_out_degree']:.2f}",
                    int(r["hop_diameter"]), f"{100 * r['oneway_frac']:.0f}%"] for _, r in gstats.iterrows()]))
        add("")
    add(f"The main experiments use the synthetic city (n = {M['n']:,}): a perturbed street grid with arterial "
        "roads, one-way streets and a river crossed by four bridges. Real networks are OpenStreetMap drivable "
        "roads (© OpenStreetMap contributors, ODbL), cached in `data/`, restricted to the largest strongly "
        "connected component; travel times come from osmnx speed estimates.\n")

    # ------------------------------------------------------------ headline
    add("## 3. Headline results\n")
    noop = {m: row(m, lo)["frac_noop"] for m in modes if m != "tree"}
    t1 = row("tree", lo)
    add(f"- **No-op trap.** {100 * min(noop.values()):.0f}–{100 * max(noop.values()):.0f}% of random "
        f"single-road closures change no distance at all (the road is on no shortest path), so repair exits "
        f"immediately. Their median ‘speed-up’ of up to {x(max(row(m, lo)['speedup_med'] for m in noop))} is "
        "meaningless; we therefore report *effective* updates (something changed) separately.")
    add(f"- **One road that matters.** Blocking a single shortest-path-tree edge, per-edge repair was "
        f"**{x(t1['speedup_eff_med'])}** faster than full Dijkstra "
        f"({t1['t_repair_eff_ms']:.3f} ms vs {t1['t_full_ms']:.1f} ms, medians).")
    if "batch" in methods:
        ratio = {m: row(m, hi)["t_repair_ms"] / row(m, hi, "batch")["t_repair_ms"] for m in modes}
        best = max(ratio, key=ratio.get)
        add(f"- **Batch repair** is up to **{x(ratio[best])}** faster than per-edge repair at {hi:,} changed "
            f"edges ({MODE[best].lower()}), because overlapping affected regions are re-solved only once.")
    add("- **Break-even.** Repair stops paying off once a disruption is large: see the table below. "
        "Beyond that size, recomputing from scratch is cheaper.\n")
    rows = [[MODE[m]] + [be(M["crossover"]["speedup_med"][mt].get(m), hi) for mt in methods]
            + [be(M["crossover"]["speedup_eff_med"]["sequential"].get(m), hi)] for m in modes]
    add(table(["Disruption"] + [f"Break-even, {METHOD[mt]} (edges)" for mt in methods]
              + ["Per-edge, effective trials only"], rows))
    add("")

    # ------------------------------------------------------------ figures
    add("## 4. Figures\n")
    add("### Figure 1 – Speed-up versus disruption size\n")
    add(f"![speed-up]({fig('fig1_speedup_vs_size.png')})\n")
    add("One panel per disruption model; blue = per-edge repair, red = batch repair; solid = all trials "
        "(band = inter-quartile range), dotted = effective trials only; above the black line repair is faster "
        "than recomputing.\n")
    show = [s for s in (1, 10, 100, 1000) if s in sizes] or sizes[:4]
    add(table(["Edges changed"] + [MODE[m] for m in modes],
              [[f"{k:,}"] + [f"{x(row(m, k)['speedup_med'])} / {x(row(m, k)['speedup_eff_med'])} "
                             f"({100 * row(m, k)['frac_noop']:.0f}% no-op)" for m in modes] for k in show]))
    add("\n*Median speed-up of per-edge repair: all trials / effective trials (share of no-op trials).*\n")
    add("### Figure 2 – Time per disruption\n")
    add(f"![runtime]({fig('fig2_runtime_vs_size.png')})\n")
    add("Dijkstra's cost (black) is flat; repair cost grows with the number of changed roads.\n")
    add("### Figure 3 – How much of the map is affected\n")
    add(f"![affected]({fig('fig3_affected_fraction.png')})\n")
    add("Mean percentage of intersections whose travel time changes. Repair work is proportional to this.\n")
    add("### Figure 4 – Scaling with network size\n")
    add(f"![scaling]({fig('fig4_scaling_with_n.png')})\n")
    one = sc[(sc["scenario"] == "single tree-edge closure") & (sc["method"] == "sequential")].groupby("n").median(
        numeric_only=True).sort_index()
    add(f"From {int(one.index[0]):,} to {int(one.index[-1]):,} nodes, full Dijkstra became "
        f"{one['t_full'].iloc[-1] / one['t_full'].iloc[0]:.0f}× slower while repairing a single tree-edge "
        f"closure changed by {one['t_repair'].iloc[-1] / one['t_repair'].iloc[0]:.1f}×: repair cost depends on "
        "how much changes, not on the size of the map.\n")
    add("### Figure 5 – Which closures cause big ripples\n")
    add(f"![ripple]({fig('fig5_ripple.png')})\n")
    close = float(((rp["affected"] / rp["subtree"]).clip(upper=1) >= 0.9).mean())
    med = rp.groupby("cls")["affected"].median()
    add(f"{len(rp)} single tree-edge closures. The number of changed distances never exceeded the size of the "
        f"shortest-path-tree subtree below the closed road (the proof's bound) and was within 10% of it in "
        f"{100 * close:.0f}% of cases. Median ripple by road class: "
        + ", ".join(f"{c} {int(v)}" for c, v in med.items()) + ".\n")
    add("### Figure 6 – Anatomy of one accident\n")
    add(f"![heatmap]({fig('fig6_heatmap.png')})\n")
    add(f"The worst of 40 random 80-road accident zones: {M['heatmap_net_changed']:,} of {M['n']:,} "
        f"intersections ({100 * M['heatmap_net_changed'] / M['n']:.0f}%) get a new travel time; colour = "
        "extra minutes from the depot.\n")
    if fleet is not None:
        add("### Figure 7 – Fleet rerouting\n")
        add(f"![fleet]({fig('fig7_fleet.png')})\n")
        st = fleet.groupby(["placement", "size"]).agg(
            used=("used_closed", "mean"), changed=("routes_changed", "mean"), delayed=("delayed", "mean"),
            stranded=("stranded", "mean")).reset_index()
        d = fleet[fleet["delayed"] > 0].groupby(["placement", "size"])["extra_min_mean"].median()
        add(f"{int(fleet['vehicles'].iloc[0])} delivery vehicles; one accident zone per trial, placed anywhere or "
            "centred on a vehicle's route. Means over trials:\n")
        add(table(["Accident placed", "Roads", "Route used a closed road", "Rerouted", "Delayed",
                   "Median extra minutes", "Stranded"],
                  [[r["placement"], int(r["size"]), f"{r['used']:.1f}", f"{r['changed']:.1f}", f"{r['delayed']:.1f}",
                    f"{d.get((r['placement'], r['size']), 0):.1f}", f"{r['stranded']:.1f}"] for _, r in st.iterrows()]))
        add("")
    if p2p is not None:
        add("### Figure 8 – One vehicle's route: LPA\\* vs A\\* vs repair\n")
        add(f"![p2p]({fig('fig8_point_to_point.png')})\n")
        t = p2p.groupby(["scenario", "phase", "method"])["time"].median().unstack() * 1e3
        cols = ["full Dijkstra", "Dijkstra to t", "A*", "batch repair", "LPA*"]
        add(table(["Disruption", "Phase"] + cols,
                  [[s, "blocking" if ph == "block" else "clearing"] + [f"{r[c]:.2f} ms" for c in cols]
                   for (s, ph), r in t.iterrows()]))
        b = t.xs("block", level="phase")
        add(f"\nLPA\\* beat A\\* from scratch in {(b['LPA*'] < b['A*']).sum()} of {len(b)} blocking scenarios: "
            "when a road on the route is blocked, LPA\\* must first invalidate and then rebuild the part of its "
            "search beyond the closure, which in pure Python costs about as much as searching again.\n")
    if cross is not None and gstats is not None and (gstats["source"] == "OpenStreetMap").any():
        add("### Figure 9 – Synthetic versus real networks\n")
        add(f"![cross]({fig('fig9_cross_graph.png')})\n")
        xg = M.get("crossgraph", {})
        rows = []
        for gname in gstats["graph"]:
            for m in ("tree", "cluster"):
                d = cross[(cross["graph"] == gname) & (cross["mode"] == m) & (cross["phase"] == "block")
                          & (cross["method"] == "sequential")].sort_values("size")
                if d.empty:
                    continue
                top = int(d["size"].max())
                rows.append([gname.replace("_", " "), MODE[m], x(d.iloc[0]["speedup_eff_med"]),
                             be(xg.get(gname, {}).get("sequential", {}).get(m), top),
                             be(xg.get(gname, {}).get("batch", {}).get(m), top)])
        add(table(["Network", "Disruption", "Speed-up, 1 road", "Break-even per-edge", "Break-even batch"], rows))
        add("")
    if closure is not None:
        add("### Closure model: 50× slower versus deleted\n")
        c = closure[closure["method"] == "batch"].groupby(["closure", "mode", "size"]).agg(
            net=("net_changed", "mean"), stranded=("stranded", "mean")).reset_index()
        add(table(["Closure model", "Disruption", "Roads", "Intersections changed", "Stranded"],
                  [[r["closure"], MODE[r["mode"]], int(r["size"]), f"{r['net']:.1f}", f"{r['stranded']:.1f}"]
                   for _, r in c.iterrows()]))
        add("\nThe same roads are closed under both models. The affected region is nearly identical; deletion "
            "additionally strands intersections that have no other way in.\n")
    mk = M.get("marks")
    if mk:
        add("### Implementation detail\n")
        add(f"Replacing per-call Python `set()` objects with reusable generation-stamped arrays changed the total "
            f"time for {mk['n']} single closures from {mk['total_ms_sets']:.1f} ms to {mk['total_ms_arrays']:.1f} ms "
            f"({100 * (1 - mk['total_ms_arrays'] / mk['total_ms_sets']):.0f}% less).\n")

    # ------------------------------------------------------------ rest
    add("## 5. Limitations\n")
    add("- Pure Python: absolute times and exact break-even sizes would move in C++/Rust; the comparisons "
        "between methods implemented in the same style are what the study supports.\n"
        "- One depot (single source); random disruption models, not calibrated on real incident data.\n"
        "- The straight-line A\\*/LPA\\* heuristic is calibrated to the fastest road and is therefore weak.\n"
        "- See *Threats to validity* in the report for the full list.\n")
    add("## 6. Files\n")
    add(table(["File", "Content"], [
        ["`report/Rush_Hour_Rerouting_Report.docx`", "full report: algorithms, proofs, complexity, all results"],
        ["`results/meta.json`", "parameters, break-even points, git commit, command line"],
        ["`results/summary_main.csv`", "medians/IQRs per disruption model, size, method (all vs effective)"],
        ["`results/raw_*.csv`", "one row per trial for every experiment"],
        ["`results/graph_stats.csv`, `summary_crossgraph.csv`", "real-network comparison"],
        ["`results/fig1…fig9*.png`", "the figures above"],
        ["`data/*.graphml`", "cached OpenStreetMap networks (© OpenStreetMap contributors, ODbL)"],
    ]))
    add("\nReproduce everything with `pip install -r requirements.txt` and `python run_all.py` "
        "(the quick smoke test is `python run_all.py --quick`).\n")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(ROOT, "results"))
    ap.add_argument("--out", default=os.path.join(ROOT, "RESULTS_AND_INFORMATION.md"))
    a = ap.parse_args()
    build(a.results, a.out)
    print("Wrote", os.path.abspath(a.out))


if __name__ == "__main__":
    main()
